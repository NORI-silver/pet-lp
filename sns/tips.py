def width(s):
    return sum(1 if ord(c) < 0x1100 else 2 for c in s)


def main():
    dry = "--dry" in sys.argv
    pj = os.path.join(HERE, "posts.json")
    data = json.load(open(pj, encoding="utf-8"))
    posts = data["posts"]
    have = {p.get("key") for p in posts}
    no = max(p["no"] for p in posts)
    pool = {"dog": DOG, "cat": CAT, "small": SMALL}
    used = {"dog": 0, "cat": 0, "small": 0}
    bad, new = [], []
    for key, animal, text in TIPS:
        w = width(text)
        ng = [b for b in BAN if b in text]
        if w > 280 or ng:
            bad.append((key, w, ng))
            continue
        photo = pool[animal][used[animal] % len(pool[animal])]
        used[animal] += 1
        if f"tip:{key}" in have:
            continue
        no += 1
        head = text.split("\n")[0]
        new.append({"no": no, "key": f"tip:{key}", "kind": "tip", "photo": photo, "x": text,
                    "tag": f"豆知識・{head[:16]}", "head": head, "alt": {"dog": "犬の写真", "cat": "猫の写真", "small": "小さな動物の写真"}[animal]})
    for k in bad:
        print("長すぎるか使わない言葉:", k)
    print("足す", len(new))
    if bad:
        return 1
    if dry:
        for p in new[:3]:
            print("----", width(p["x"]), "\n" + p["x"])
        return 0
    posts.extend(new)
    json.dump(data, open(pj, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    open(pj, "a", encoding="utf-8").write("\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
