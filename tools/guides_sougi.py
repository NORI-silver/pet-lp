def _typ(seg):
    if ("納骨" in seg or "供養" in seg) and "火葬" not in seg: return None
    if _re.search(r"立会|立ち会|お立会", seg): return "tachiai"
    if _re.search(r"訪問|出張火葬|移動火葬", seg): return "houmon"
    if _re.search(r"合同", seg): return "goudou"
    if _re.search(r"一任|おまかせ|お任せ|一人|個別", seg): return "kobetsu"
    return None

def _prices(p):
    # 「個別火葬 小型犬 20,000円・合同火葬 11,000円」のような文から、火葬の種類ごとに最初（いちばん小さい区分）の金額を取る
    got = {}
    for seg in _re.split(r"[・、，]|(?<=円)\s", p or ""):
        m = _re.search(r"([\d,]{4,})円", seg); t = _typ(seg)
        if m and t and t not in got: got[t] = int(m.group(1).replace(",", ""))
    return got

_P = [_prices(f.get("price")) for f in _FAC]
def _yen(x): return f"{int(x):,}円"
def _stat(t):
    v = sorted(g[t] for g in _P if t in g)
    return dict(n=len(v), lo=_yen(v[0]), q1=_yen(v[len(v) // 4]), med=_yen(_st.median(v)), q3=_yen(v[(3 * len(v)) // 4]), hi=_yen(v[-1]))
SG, SK, ST = _stat("goudou"), _stat("kobetsu"), _stat("tachiai")
_gk = [g["kobetsu"] - g["goudou"] for g in _P if "goudou" in g and "kobetsu" in g]
_kt = [g["tachiai"] - g["kobetsu"] for g in _P if "tachiai" in g and "kobetsu" in g]
N_GK, D_GK = len(_gk), _yen(_st.median(_gk))
N_KT, D_KT = len(_kt), _yen(_st.median(_kt))
N_FAC = len(_FAC)
N_PREF_FAC = len({f["pref"] for f in _FAC})
N_PRICED = sum(1 for f in _FAC if f.get("price"))
N_KG = sum(1 for f in _FAC if "kg" in (f.get("price") or ""))
N_TAX = sum(1 for f in _FAC if "税込" in (f.get("price") or "") or "税込み" in (f.get("price") or ""))
def _sv(x): return sum(1 for f in _FAC if x in f["services"])
def _kd(x): return sum(1 for f in _FAC if x in f["kinds"])
N_SV = {k: _sv(k) for k in ("合同火葬", "個別火葬", "立ち会い火葬", "訪問火葬", "お迎え", "納骨")}
