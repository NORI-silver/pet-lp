N_CORE = sum(1 for c in _C if c.get("kind") == "中核市")

_SENIOR = re.compile(r"(5[5-9]|[6-9]\d)歳|高齢")
_AGE = re.compile(r"(\d+)歳(以上|を超える|以下|まで|未満)?")
_RANGE = re.compile(r"〜(\d+)歳(以下|まで|未満)?")
_BACK = re.compile(r"代わり|後見|保証|誓約|同意|承諾|引受|引き受け|補助|世話人|協力|支え|継続|準譲受|申立|身元|サポート|預け先|引き継|了承|相談|次に飼う|後継")
_OLDPET = re.compile(r"10歳以上の|おおむね10歳以上")
# 読み違えを直す（自治体の名前 → 直すこと）
_FIX = {
    "岡崎市": dict(age=None, back=True),  # 「20〜55歳未満の第2飼養責任者」は年齢に関係なく全員に求める代わりの人の条件で、何歳からではない
    "岡山市": dict(back=True),  # 「近くの親戚と世話できるなら例外」と書いている
}

def _th(x):
    """条件の文から「何歳から条件がつくか」を読む（ペットの年齢の文は除く）"""
    if _OLDPET.search(x): return None
    for m in list(_RANGE.finditer(x)) + list(_AGE.finditer(x)):
        n, s = int(m.group(1)), m.group(2) or ""
        if n < 55: continue
        if m.re is _RANGE: return n if s == "未満" else n + 1
        return {"以上": n, "を超える": n + 1, "以下": n + 1, "まで": n + 1, "未満": n}.get(s, n)
    return None

def _name(c): return c["city"] or c["pref"]

ROWS = []  # (自治体, 種類, 何歳から, 代わりの人の道, 年上の子の道, 条件の文)
for c in _C:
    sc = [x for x in c["conds"] if _SENIOR.search(x)]
    if not sc: continue
    ts = [t for t in map(_th, sc) if t]
    r = dict(name=_name(c), pref=c["pref"], kind=c["kind"], age=min(ts) if ts else None,
             back=any(_BACK.search(x) for x in sc), oldpet=any(_OLDPET.search(x) for x in c["conds"]), conds=sc, url=c["url"])
    r.update(_FIX.get(r["name"], {}))
    ROWS.append(r)

N_SENIOR = len(ROWS)
P_SENIOR = round(N_SENIOR * 100 / N_ALL)
N_BACK = sum(1 for r in ROWS if r["back"])
N_LIMIT = sum(1 for r in ROWS if not r["back"] and not r["oldpet"])
N_OLDPET = sum(1 for r in ROWS if r["oldpet"])
OLDPET = [r["name"] for r in ROWS if r["oldpet"]]
_AGES = [r["age"] for r in ROWS if r["age"]]
N_AGE = len(_AGES)
A60 = sum(1 for a in _AGES if a <= 60)
A61 = sum(1 for a in _AGES if 61 <= a <= 64)
A65 = sum(1 for a in _AGES if a == 65)
A66 = sum(1 for a in _AGES if a >= 66)
N_SINGLE = sum(1 for c in _C if any(re.search(r"一人|ひとり|単身", x) for x in c["conds"]))
def _cnt(p): return sum(1 for c in _C if any(re.search(p, x) for x in c["conds"]))
N_KOSHU = _cnt(r"講習")
N_FAMILY = _cnt(r"家族全員|家族の同意|同居.*(賛成|同意)")
N_HOME = _cnt(r"賃貸|ペット可|住まい|住宅|集合住宅|借家")
N_INDOOR = _cnt(r"室内")
N_SPAY = _cnt(r"不妊|去勢")

def _pct(a, b): return f"{round(a * 100 / b)}%" if b else "—"
def _agetxt(a): return f"{a}歳から" if a else "年齢は書いていない（「高齢」）"

