import json, os, re

_J = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "joto.json"), encoding="utf-8"))
_C = _J["centers"]
N_ALL = len(_C)
N_PREF = sum(1 for c in _C if c.get("kind") == "都道府県")
