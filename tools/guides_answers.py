def _summary(sections):
    """最初の節の1つめが「まとめ：…」の箱なら、その文を答えの箱にする"""
    h, bs = sections[0]
    b0 = bs[0] if bs else None
    if not (isinstance(b0, tuple) and b0[0] == "tip" and str(b0[1]).startswith("まとめ：")): return None
    t = str(b0[1])[len("まとめ："):].strip()
    j = t.find("。")
    title, rest = (t[:j + 1], t[j + 1:].strip()) if 0 < j < len(t) - 1 else (t, "")
    ans = ("結論：" + title, ([rest] if rest else []) + (list(bs[1:]) if h == "まとめ" else []))
    return [ans] + ([] if h == "まとめ" else [(h, list(bs[1:]))]) + list(sections[1:])


def apply(guides):
    out = []
    for g in guides:
        secs = g.get("sections") or []
        if secs and not _V.is_answer(secs[0][0]):
            new = _summary(secs)
            if new is None and g["slug"] in ANSWERS:
                h, items = ANSWERS[g["slug"]]
                new = [(h, [("ul", items)])] + list(secs)
            if new is not None:
                g = dict(g, sections=new)
        out.append(g)
    return out
