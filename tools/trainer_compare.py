"""The first-visit comparison is separate from the general trainer directory."""
import json
from pathlib import Path
from html import escape
from urllib.parse import urlsplit

HERE = Path(__file__).parent

def render():
    rows = json.loads((HERE / "trainer_compare.json").read_text(encoding="utf-8"))
    cities = sorted({m["city"] for m in rows} | {c for m in rows for c in m.get("area", [])})
    opts = "".join(f'<option>{escape(c)}</option>' for c in cities)
    assert len({m["id"] for m in rows}) == len(rows)
    assert all(urlsplit(m[k]).scheme == "https" for m in rows for k in ("source", "contact"))
    return f'''<details class="tc-panel" id="first-lesson"><summary><strong>初回メニューと料金をくらべる</strong><small>まずは千葉県の一部。実技・相談・預かりの違いが分かります。</small></summary>
<form class="tc-form"><div class="tc-grid">
<label>探す市区町村<select name="city" required><option value="">選んでください</option>{opts}<option value="other">千葉県内のほかの市区町村</option></select></label>
<label>受け方<select name="mode"><option value="">指定なし</option><option value="visit">出張</option><option value="school">教室に通う</option><option value="day">預ける</option></select></label>
<label>困りごと<select name="issue"><option value="">指定なし</option><option value="bark">吠える</option><option value="bite">噛む</option><option value="walk">散歩・引っ張り</option><option value="toilet">トイレ</option><option value="puppy">子犬のしつけ</option><option value="other">その他</option></select></label>
<label>犬種（任意）<input name="breed" maxlength="45" placeholder="例：ラブラドール"></label>
<label>体重 kg（任意）<input name="weight" type="number" min="0.1" max="120" step="0.1" inputmode="decimal" placeholder="例：30"></label>
<label>年齢・月齢（任意）<input name="age" type="number" min="0" max="360" step="1" inputmode="numeric" placeholder="例：3歳なら36"></label>
</div><button type="submit" disabled>受けられるメニューと初回料金を見る</button>
<p class="tc-help">ここでは予約や情報の送信はしません。空き・受け入れ・料金の最終確認は事業者へ。</p></form>
<p class="tc-status" tabindex="-1" aria-live="polite"></p><div class="tc-results"></div>
<noscript><p>比較にはJavaScriptが必要です。下の一覧はそのまま利用できます。</p></noscript>
</details>'''

def add(h):
    marker = '<div class="emg">'
    assert marker in h
    return h.replace(marker, marker + render(), 1).replace(
        '</head>', '<link rel="stylesheet" href="/dog-trainer/first-lesson.css"><script src="/dog-trainer/first-lesson-data.js" defer></script><script src="/dog-trainer/first-lesson.js" defer></script>\n</head>', 1)


def write_data(root):
    rows = json.loads((HERE / "trainer_compare.json").read_text(encoding="utf-8"))
    data = json.dumps(rows, ensure_ascii=False, separators=(",", ":"))
    (Path(root) / "dog-trainer/first-lesson-data.js").write_text(
        "/* Generated by tools/trainer_compare.py */\nwindow.trainerFirstLessonMenus = " + data + ";\n", encoding="utf-8")
