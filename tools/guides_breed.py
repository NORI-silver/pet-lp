def _price(tiers, kg):
    for up, yen in tiers:
        if kg < up: return yen
    return None

def _yen(n): return f"{n:,}円"

def cremation_rows():
    rows = []
    for key, lab, lo, hi, rep in CREM_SIZES:
        got = [(n, kind, u, _price(t, rep)) for n, kind, u, t in CREMATION]
        got = [x for x in got if x[3]]
        vals = sorted(x[3] for x in got)
        med = vals[len(vals) // 2] if len(vals) % 2 else (vals[len(vals) // 2 - 1] + vals[len(vals) // 2]) // 2
        bars = {"title": f"体重{rep}kgの子の個別火葬（{len(got)}施設、北から順）",
                "rows": [(n, y, _yen(y)) for n, _, _, y in got],
                "note": "施設ごとに「個別」の中身（立ち会い・骨つぼ・お迎え）がちがいます。種類は下の注のとおりです。"}
        items = [f"公式サイトに体重ごとの料金がある{len(got)}施設では、{_yen(vals[0])}〜{_yen(vals[-1])}、真ん中は{_yen(med)}でした",
                 ("bars", bars)]
        if lo >= 15:
            items.append("合同火葬（ほかの子と一緒）ができない重さがある施設があります：フジパーク ペット霊園は20kg以上、四日市ペット斎場は30kg以上で合同火葬がありません。費用をおさえたいときは先に確かめます")
